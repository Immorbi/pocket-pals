const POOLS: Record<ChatterKind, string[]> = { praise: PRAISE, joke: JOKES, fact: FACTS };
const KINDS: ChatterKind[] = ['praise', 'joke', 'fact'];

/** Avoids repeating the previous kind so praise/joke/fact keep alternating. */
export function nextChatter(previous: ChatterLine | null, gender: 'f' | 'm'): ChatterLine {
  const available = previous ? KINDS.filter((k) => k !== previous.kind) : KINDS;
  const kind = available[Math.floor(Math.random() * available.length)];
  const pool = POOLS[kind].map((t) => render(t, gender)).filter((text) => text !== previous?.text);
  return { kind, text: pool[Math.floor(Math.random() * pool.length)] };
}
